let currentLanguage = "it";

function setLanguage(lang) {
  currentLanguage = lang === "en" ? "en" : "it";
  const words = translations[currentLanguage];

  document.documentElement.lang = currentLanguage;
  document.title = currentLanguage === "it"
    ? "Fara Safari Tours | Safari in Kenya"
    : "Fara Safari Tours | Kenya Safaris";

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (words[key] !== undefined) element.textContent = words[key];
  });

  document.querySelectorAll(".lang-btn").forEach(button => {
    const active = button.dataset.lang === currentLanguage;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.getElementById("customerLanguage").value = currentLanguage;
}

document.querySelectorAll(".lang-btn").forEach(button => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

